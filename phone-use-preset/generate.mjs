// Rebuild phone-use-preset/cordis.patch.yml from the dsh that is installed here.
//
// A preset is no longer a `$DSH_HOME/.agent-presets/<id>/` directory (0.1.7 stopped
// reading that); it is an `@deepseek-ai/dsh-agent-preset` declaration carried by a
// bundle patch. This preset must stay "the shipped `standard` composition plus one
// row", so the patch is GENERATED from the shipped standard rather than kept as a
// frozen copy: 0.1.7 added `tool-plugin-manager` to standard, and a copy taken from
// an older release silently drops whatever the next release adds.
//
//   node phone-use-preset/generate.mjs [--dsh-dir ~/dsh] [--out <file>]
//
// The row this adds lives in `phone-use.row.yml` beside this file. Anchors are
// asserted, so a release that reshapes standard.patch.yml fails loudly here instead
// of producing a preset that mounts without the row.
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const argv = process.argv.slice(2)
const option = (name, fallback) => {
  const at = argv.indexOf(name)
  return at >= 0 && argv[at + 1] !== undefined ? argv[at + 1] : fallback
}
const dshDir = resolve(option('--dsh-dir', process.env.DSH_DIR ?? join(process.env.HOME ?? '', 'dsh')))
const out = resolve(option('--out', join(here, 'cordis.patch.yml')))

const shippedPath = join(dshDir, 'node_modules', '@deepseek-ai', 'dsh-web-app', 'presets', 'standard.patch.yml')
if (!existsSync(shippedPath)) {
  console.error(`generate: no shipped standard preset at ${shippedPath} (pass --dsh-dir)`)
  process.exit(1)
}
let patch = readFileSync(shippedPath, 'utf8')
const row = readFileSync(join(here, 'phone-use.row.yml'), 'utf8').trimEnd()

const replaceOnce = (needle, replacement, what) => {
  const count = patch.split(needle).length - 1
  if (count !== 1) {
    console.error(`generate: expected exactly one ${what} in the shipped standard preset, found ${count}`)
    console.error('generate: this release reshaped standard.patch.yml — update this generator, do not hand-edit the output')
    process.exit(1)
  }
  patch = patch.replace(needle, replacement)
}

replaceOnce(
  `# Agent preset standard: one \`@deepseek-ai/dsh-agent-preset\` declaration inserted
# after the web patch. Edits saved from the Web editor override this row's
# \`config.plugins\` by id from the profile patch.
`,
  `# PhoneUse agent preset: the harness's own \`standard\` composition plus the row in
# phone-use.row.yml, giving a session the eight \`phone_*\` tools over the paired
# Termux \`adb\`.
#
# GENERATED by phone-use-preset/generate.mjs from this dsh's shipped standard preset
# — do not hand-edit: re-run the generator instead. It replaces the legacy
# \`$DSH_HOME/.agent-presets/phone-use/\` directory (preset.yml + agent.cordis.yml),
# which 0.1.7 no longer reads.
`,
  'header',
)
replaceOnce('    - id: preset-standard\n', '    - id: preset-phone-use\n', 'declaration row')
replaceOnce(
  `      config:
        id: standard
        order: 1
        plugins:
`,
  `      config:
        id: phone-use
        name: 标准模式 + PhoneUse
        description: 标准模式的全部能力，外加 PhoneUse：通过已配对的 adb 直接操作这台安卓手机——截屏并以图像交给模型、读取可点击元素的真实像素坐标、点击、滑动、按键、输入文本、启动与停止应用。
        plugins:
`,
  'declaration config',
)

const indented = row
  .split('\n')
  .map((line) => (line.trim() === '' ? line : `          ${line}`))
  .join('\n')

writeFileSync(out, `${patch.trimEnd()}\n${indented}\n`)
console.log(`generate: wrote ${out} (${(row.match(/^- id: /gm) ?? []).length} added row)`)
